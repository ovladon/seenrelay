import { writeFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';

const baseUrlRaw = process.env.SEENRELAY_LOAD_BASE_URL?.trim();
if (!baseUrlRaw) {
  throw new Error('SEENRELAY_LOAD_BASE_URL is required. Point it at an isolated Preview deployment first.');
}

const baseUrl = new URL(baseUrlRaw);
const isProduction = baseUrl.hostname === 'seenrelay.com' || baseUrl.hostname === 'www.seenrelay.com';
if (isProduction && process.env.SEENRELAY_LOAD_ALLOW_PRODUCTION !== 'true') {
  throw new Error('Refusing to load-test Production. Set SEENRELAY_LOAD_ALLOW_PRODUCTION=true only after explicit operator approval.');
}
if (!['https:', 'http:'].includes(baseUrl.protocol)) throw new Error('SEENRELAY_LOAD_BASE_URL must use http or https.');

const profiles = {
  smoke: [{ cases: 10, concurrency: 2 }],
  ramp: [
    { cases: 50, concurrency: 5 },
    { cases: 200, concurrency: 10 },
    { cases: 500, concurrency: 20 },
  ],
  scale: [
    { cases: 100, concurrency: 10 },
    { cases: 500, concurrency: 25 },
    { cases: 1500, concurrency: 50 },
    { cases: 4000, concurrency: 100 },
  ],
};

function parseStages(raw) {
  const stages = raw.split(',').map((part) => {
    const match = part.trim().match(/^(\d+)@(\d+)$/);
    if (!match) throw new Error('SEENRELAY_LOAD_STAGES must look like 100@10,1000@50 (cases@concurrency).');
    const cases = Number.parseInt(match[1], 10);
    const concurrency = Number.parseInt(match[2], 10);
    if (!Number.isSafeInteger(cases) || cases <= 0 || !Number.isSafeInteger(concurrency) || concurrency <= 0) {
      throw new Error('SEENRELAY_LOAD_STAGES values must be positive integers.');
    }
    if (concurrency > cases) throw new Error('SEENRELAY_LOAD_STAGES concurrency cannot exceed cases in a stage.');
    return { cases, concurrency };
  });
  if (stages.length === 0 || stages.length > 12) throw new Error('SEENRELAY_LOAD_STAGES must contain 1..12 stages.');
  return stages;
}

const profileName = process.env.SEENRELAY_LOAD_PROFILE?.trim() || 'smoke';
const customStagesRaw = process.env.SEENRELAY_LOAD_STAGES?.trim();
const selectedProfile = customStagesRaw ? parseStages(customStagesRaw) : profiles[profileName];
if (!selectedProfile) throw new Error(`Unknown SEENRELAY_LOAD_PROFILE=${profileName}. Use smoke, ramp, scale, or SEENRELAY_LOAD_STAGES.`);

const networkMode = process.env.SEENRELAY_LOAD_NETWORK_MODE?.trim() || 'shared';
if (!['shared', 'distributed'].includes(networkMode)) {
  throw new Error('SEENRELAY_LOAD_NETWORK_MODE must be shared or distributed.');
}
if (isProduction && networkMode === 'distributed') {
  throw new Error('Distributed network simulation is Preview-only; Production does not honor the test-network header.');
}

function parsePositiveInt(name, fallback) {
  const raw = process.env[name]?.trim();
  if (!raw) return fallback;
  const parsed = Number.parseInt(raw, 10);
  if (!Number.isSafeInteger(parsed) || parsed <= 0) throw new Error(`${name} must be a positive integer.`);
  return parsed;
}

function parseNonNegativeNumber(name, fallback) {
  const raw = process.env[name]?.trim();
  if (!raw) return fallback;
  const parsed = Number.parseFloat(raw);
  if (!Number.isFinite(parsed) || parsed < 0) throw new Error(`${name} must be a non-negative number.`);
  return parsed;
}

const timeoutMs = parsePositiveInt('SEENRELAY_LOAD_TIMEOUT_MS', 10_000);
const p95LimitMs = parsePositiveInt('SEENRELAY_LOAD_P95_LIMIT_MS', 1_500);
const max5xxRate = parseNonNegativeNumber('SEENRELAY_LOAD_MAX_5XX_RATE', 0.001);
const maxUnexpectedRate = parseNonNegativeNumber('SEENRELAY_LOAD_MAX_UNEXPECTED_RATE', 0);
const outputPath = process.env.SEENRELAY_LOAD_OUTPUT?.trim() || 'seenrelay-load-report.json';
const maxAgeSeconds = parsePositiveInt('SEENRELAY_LOAD_MAX_AGE_SECONDS', 3600);
const runKey = process.env.SEENRELAY_LOAD_RUN_KEY?.trim() || `${Date.now()}-${randomUUID().slice(0, 8)}`;
const previewNetworkHint = `seenrelay-load-${runKey}`;

// This reserved source marker is recognized by getAdminAdoptionData(). It keeps every observation
// generated by this harness in raw operational telemetry while excluding it from external-adoption
// classification. Do not remove it from load-test facts.
const benchmarkMarker = `seenrelay_internal_benchmark=load-${encodeURIComponent(runKey)}`;

const report = {
  schema_version: 1,
  benchmark: 'controlled-seenrelay-load-v1',
  run_key: runKey,
  started_at: new Date().toISOString(),
  target: baseUrl.origin,
  production_target: isProduction,
  profile: customStagesRaw ? 'custom' : profileName,
  network_mode: networkMode,
  configured_stages: selectedProfile,
  maximum_operations_if_every_case_completes: selectedProfile.reduce((sum, stage) => sum + stage.cases * 3, 0),
  safety: {
    production_requires_explicit_opt_in: true,
    distributed_network_simulation_preview_only: true,
    adoption_marker: 'seenrelay_internal_benchmark',
    timeout_ms: timeoutMs,
    p95_limit_ms: p95LimitMs,
    max_5xx_rate: max5xxRate,
    max_unexpected_rate: maxUnexpectedRate,
  },
  stages: [],
  stopped_early: false,
  stop_reason: null,
};

function percentile(values, p) {
  if (values.length === 0) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const index = Math.min(sorted.length - 1, Math.max(0, Math.ceil((p / 100) * sorted.length) - 1));
  return Number(sorted[index].toFixed(3));
}

function summarizeLatencies(values) {
  return {
    samples: values.length,
    p50_ms: percentile(values, 50),
    p95_ms: percentile(values, 95),
    p99_ms: percentile(values, 99),
    max_ms: values.length ? Number(Math.max(...values).toFixed(3)) : null,
  };
}

function increment(map, key) {
  const normalized = String(key ?? 'null');
  map[normalized] = (map[normalized] || 0) + 1;
}

async function requestJson(worker, endpoint, payload) {
  const headers = new Headers({
    'content-type': 'application/json',
    'x-seenrelay-client': `controlled-load-${runKey}-worker-${worker.id}`,
  });
  if (worker.lease) headers.set('x-seenrelay-lease', worker.lease);
  if (!isProduction) {
    const networkHint = networkMode === 'distributed'
      ? `${previewNetworkHint}-worker-${worker.id}`
      : previewNetworkHint;
    headers.set('x-seenrelay-test-network', networkHint);
  }

  const started = performance.now();
  try {
    const response = await fetch(new URL(endpoint, baseUrl), {
      method: 'POST',
      headers,
      body: JSON.stringify(payload),
      signal: AbortSignal.timeout(timeoutMs),
    });
    const latencyMs = performance.now() - started;
    const text = await response.text();
    let body = {};
    try { body = text ? JSON.parse(text) : {}; } catch { body = { raw: text.slice(0, 1000) }; }
    const lease = response.headers.get('x-seenrelay-lease');
    if (lease) worker.lease = lease;
    return {
      ok: response.ok,
      status: response.status,
      latency_ms: latencyMs,
      error_code: body?.error?.code || null,
      body,
    };
  } catch (error) {
    return {
      ok: false,
      status: 0,
      latency_ms: performance.now() - started,
      error_code: error?.name === 'TimeoutError' ? 'CLIENT_TIMEOUT' : 'CLIENT_FETCH_ERROR',
      body: { error: { detail: error instanceof Error ? error.message : String(error) } },
    };
  }
}

function makeFact(stageIndex, caseIndex) {
  const source = `https://example.com/load-fixture?${benchmarkMarker}&stage=${stageIndex}&case=${caseIndex}`;
  return {
    subject: 'SeenRelay controlled load fixture',
    predicate: 'load.fixture.value.current',
    source,
    qualifiers: { benchmark: 'controlled-load-v1' },
    locator: { scheme: 'source_key', value: 'fixture-value' },
  };
}

function classifyResponse(stage, operation, response, expectedBodyStatus = null) {
  stage.requests += 1;
  stage.latencies_all.push(response.latency_ms);
  increment(stage.http_statuses, response.status);
  if (response.error_code) increment(stage.error_codes, response.error_code);
  if (response.status >= 500) stage.http_5xx += 1;
  if (response.status === 429) stage.http_429 += 1;
  if (response.status === 0) stage.client_failures += 1;
  if (response.ok) stage.latencies_success.push(response.latency_ms);

  const recognizedRateLimit = response.status === 429
    && ['HIVE_ADMISSION_LIMITED', 'HIVE_RATE_LIMITED'].includes(response.error_code);

  if (response.ok && expectedBodyStatus) {
    const actual = operation === 'observe'
      ? (response.body?.accepted === true || response.body?.accepted === false ? 'OBSERVED' : null)
      : response.body?.status;
    if (actual !== expectedBodyStatus) {
      stage.semantic_mismatches += 1;
      increment(stage.semantic_mismatch_types, `${operation}:${expectedBodyStatus}->${actual}`);
    }
  } else if (!response.ok && !recognizedRateLimit) {
    stage.unexpected_responses += 1;
  }

  return recognizedRateLimit;
}

async function runCase(stage, stageIndex, caseIndex, worker) {
  const fact = makeFact(stageIndex, caseIndex);
  const value = `value-${runKey}-${stageIndex}-${caseIndex}`;

  const firstCheck = await requestJson(worker, '/v1/check', {
    fact,
    known_value: value,
    max_age_seconds: maxAgeSeconds,
  });
  const firstLimited = classifyResponse(stage, 'check-initial', firstCheck, firstCheck.ok ? 'UNKNOWN' : null);
  if (!firstCheck.ok) return firstLimited ? 'rate_limited' : 'failed';

  const observe = await requestJson(worker, '/v1/observe', {
    fact,
    value,
    observer_id: `controlled-load-${runKey}-worker-${worker.id}`,
    idempotency_key: `load-${runKey}-${stageIndex}-${caseIndex}`,
  });
  const observeLimited = classifyResponse(stage, 'observe', observe, observe.ok ? 'OBSERVED' : null);
  if (!observe.ok) return observeLimited ? 'rate_limited' : 'failed';

  const secondCheck = await requestJson(worker, '/v1/check', {
    fact,
    known_value: value,
    max_age_seconds: maxAgeSeconds,
  });
  const secondLimited = classifyResponse(stage, 'check-reuse', secondCheck, secondCheck.ok ? 'SAME_OBSERVED' : null);
  if (!secondCheck.ok) return secondLimited ? 'rate_limited' : 'failed';

  return 'completed';
}

async function runStage(stageIndex, config) {
  const stage = {
    stage: stageIndex + 1,
    cases_requested: config.cases,
    concurrency: config.concurrency,
    started_at: new Date().toISOString(),
    requests: 0,
    cases_completed: 0,
    cases_rate_limited: 0,
    cases_failed: 0,
    http_5xx: 0,
    http_429: 0,
    client_failures: 0,
    unexpected_responses: 0,
    semantic_mismatches: 0,
    http_statuses: {},
    error_codes: {},
    semantic_mismatch_types: {},
    latencies_all: [],
    latencies_success: [],
  };

  const workers = Array.from({ length: config.concurrency }, (_, index) => ({ id: index + 1, lease: null }));
  let nextCase = 0;
  const workerLoop = async (worker) => {
    for (;;) {
      const caseIndex = nextCase++;
      if (caseIndex >= config.cases) return;
      const outcome = await runCase(stage, stageIndex + 1, caseIndex + 1, worker);
      if (outcome === 'completed') stage.cases_completed += 1;
      else if (outcome === 'rate_limited') stage.cases_rate_limited += 1;
      else stage.cases_failed += 1;
    }
  };

  await Promise.all(workers.map(workerLoop));
  stage.completed_at = new Date().toISOString();
  stage.latency_all = summarizeLatencies(stage.latencies_all);
  stage.latency_success = summarizeLatencies(stage.latencies_success);
  delete stage.latencies_all;
  delete stage.latencies_success;

  stage.rates = {
    http_5xx: stage.requests ? stage.http_5xx / stage.requests : 0,
    unexpected: stage.requests ? stage.unexpected_responses / stage.requests : 0,
    semantic_mismatch: stage.requests ? stage.semantic_mismatches / stage.requests : 0,
  };
  stage.kill_criteria = {
    no_semantic_mismatches: stage.semantic_mismatches === 0,
    five_xx_within_limit: stage.rates.http_5xx <= max5xxRate,
    unexpected_within_limit: stage.rates.unexpected <= maxUnexpectedRate,
    success_p95_within_limit: stage.latency_success.p95_ms == null || stage.latency_success.p95_ms <= p95LimitMs,
  };
  stage.pass = Object.values(stage.kill_criteria).every(Boolean);
  return stage;
}

for (let i = 0; i < selectedProfile.length; i += 1) {
  const stage = await runStage(i, selectedProfile[i]);
  report.stages.push(stage);
  console.log(JSON.stringify({
    event: 'seenrelay_load_stage',
    stage: stage.stage,
    requests: stage.requests,
    completed: stage.cases_completed,
    rate_limited: stage.cases_rate_limited,
    failed: stage.cases_failed,
    p95_ms: stage.latency_success.p95_ms,
    http_5xx: stage.http_5xx,
    semantic_mismatches: stage.semantic_mismatches,
    pass: stage.pass,
  }));
  if (!stage.pass) {
    report.stopped_early = true;
    report.stop_reason = `stage-${stage.stage}-kill-criterion`;
    break;
  }
}

report.completed_at = new Date().toISOString();
report.total_requests = report.stages.reduce((sum, stage) => sum + stage.requests, 0);
report.total_cases_completed = report.stages.reduce((sum, stage) => sum + stage.cases_completed, 0);
report.total_429 = report.stages.reduce((sum, stage) => sum + stage.http_429, 0);
report.total_5xx = report.stages.reduce((sum, stage) => sum + stage.http_5xx, 0);
report.total_semantic_mismatches = report.stages.reduce((sum, stage) => sum + stage.semantic_mismatches, 0);
report.pass = !report.stopped_early && report.stages.length === selectedProfile.length && report.stages.every(stage => stage.pass);

await writeFile(outputPath, `${JSON.stringify(report, null, 2)}\n`);
console.log(JSON.stringify({
  event: 'seenrelay_load_complete',
  output: outputPath,
  requests: report.total_requests,
  completed_cases: report.total_cases_completed,
  rate_limited: report.total_429,
  http_5xx: report.total_5xx,
  semantic_mismatches: report.total_semantic_mismatches,
  pass: report.pass,
}));

if (!report.pass) process.exitCode = 1;
